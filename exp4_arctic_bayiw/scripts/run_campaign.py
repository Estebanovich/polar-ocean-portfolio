#!/opt/anaconda3/envs/pyocean/bin/python
"""Run a campaign of Exp. 4 MITgcm cases (thesis bay and Van Mijenfjorden): build once, then run.

Usage::

    run_campaign.py --config bay_thesis --cases '<glob>' [--np N] [--max-concurrent K]
                    [--end-time S] [--run-suffix _short2h] [--set KEY=VALUE]
                    [--skip-ok] [--dry-run]

For each case of ``--config`` matching ``<glob>`` (fnmatch over cases.yaml names, registry
order) the inputs are generated by ``gendata.make_case`` in
``<runs_root>/<case><suffix>/input/`` and run with ``scripts/run_mitgcm.sh``. The build
(``scripts/build_mitgcm.sh``, ``--mpi`` if np > 1) goes to ``<build_root>/<config>/`` and
happens once, before the first run.

Stages (as the thesis run_expand, data.stage1 / data.stage2): the stage plan of case.json
(``actual.stages``): stage 1 is forced and runs ``input/data``; the free stage (if any) runs
``input/data.free`` in ``<run>/stage2`` and restarts from the stage-1 pickups, every
``pickup*.<iter>.*`` file (the model pickup, the Orlanski OB pickups and, with sea ice,
pickup_seaice), copied, never linked; the stems that must exist are the case's ``pickup_stems``
(pfcommon.campaign.run_stages with ``plan`` and ``stage_data``). Every case gets
``run_status_final.json``.

Resource rules (global constraints): either up to 5 serial runs at a time (``--np 1
--max-concurrent K``, K <= 5) or one MPI run of 2..5 ranks; np must equal nPx * nPy of the
config's SIZE.h (4 for the thesis tiles). The campaign refuses to start while any MPI launcher
or model process runs (matched by process name), and fails if one is left behind. SIZE.h
(Nx, Ny, Nr) is checked against every case, and the run disk must have room for the inputs.

``--dry-run`` prints the selected case names on stdout and, on stderr, the plan
(``plan_campaign``): run directory, stages and action of each case, and whether a build would be
triggered. It writes nothing.

``--skip-ok`` does not rerun a case whose run directory is already OK with the same deltaT,
forced_h, t_end_h and edits (otherwise it refuses to start); the build is skipped when up to
date. ``--set KEY=VALUE`` overrides a numeric case parameter; ``--end-time S`` sets t_end_h =
S / 3600 (a short timing run with S <= forced_h has one stage). Exit code 1 if any case is not
OK. Provenance: the sha256 of the build's executable is written to ``input/case.json``
(``binary_sha256``) when the case starts.
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Callable

PKG = Path(__file__).resolve().parents[1]          # exp4_arctic_bayiw/
REPO = PKG.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from pfcommon import campaign as cp  # noqa: E402
from pfcommon.paths import EXP4_BUILDS, EXP4_RUNS  # noqa: E402
from exp4_arctic_bayiw.gendata.make_case import case_params, load_cases, make_case, stage_plan  # noqa: E402

BUILD_SH = REPO / "scripts" / "build_mitgcm.sh"
RUN_SH = REPO / "scripts" / "run_mitgcm.sh"
THREAD_ENV = {"OPENBLAS_NUM_THREADS": "1", "OMP_NUM_THREADS": "1", "VECLIB_MAXIMUM_THREADS": "1"}
SKIP_KEYS = ("deltaT", "forced_h", "t_end_h", "edits")


def _sh(cmd: list) -> int:
    env = {**os.environ, **THREAD_ENV}
    return subprocess.run([str(c) for c in cmd], env=env).returncode


def record_binary(inp: Path, build_dir: Path) -> str:
    """Write the sha256 of the build's executable into ``inp/case.json``. Returns it."""
    exe = Path(build_dir) / cp.EXE_NAME
    if not exe.is_file():
        raise RuntimeError(f"no executable in {build_dir}")
    sha = hashlib.sha256(exe.read_bytes()).hexdigest()
    cj = Path(inp) / "case.json"
    meta = json.loads(cj.read_text())
    meta.update(binary_sha256=sha, binary_path=str(exe),
                binary_recorded_at=datetime.datetime.now().isoformat(timespec="seconds"))
    cj.write_text(json.dumps(meta, indent=2, default=float))
    return sha


def _requested(spec: dict, name: str, overrides: dict | None) -> dict:
    case = spec["cases"][name]
    p = {**spec["configs"][case["config"]], **case, **(overrides or {})}
    return {k: p.get(k) for k in SKIP_KEYS}


def plan_campaign(config: str, pattern: str, np_: int, *, overrides: dict | None = None,
                  run_suffix: str = "", runs_root: Path = EXP4_RUNS, build_root: Path = EXP4_BUILDS,
                  config_root: Path | None = None, cases_file: Path | None = None,
                  skip_ok: bool = False) -> dict:
    """What run_campaign would do, without writing, building or running anything (--dry-run):
    per case the run directory, t_end_h, forced_h, deltaT, the stage plan and the action
    ('run', 'skip (already OK)' with --skip-ok, or 'refuse: ...' when an OK run has other
    parameters); and the build action, with the same rule as run_campaign: the build is skipped
    only with --skip-ok and an executable newer than every file in config/<cfg>/code built
    with/without MPI as asked (cp.build_up_to_date); with nothing to run there is no build."""
    spec = load_cases(cases_file)
    names = cp.select_cases(spec["cases"], config, pattern)
    overrides = cp.check_overrides(names, overrides, spec)
    cfg_dir = Path(config_root or PKG / "config") / config
    build_dir = Path(build_root) / config
    cases = []
    for n in names:
        rd = Path(runs_root) / f"{n}{run_suffix}"
        p = case_params(spec, n, overrides)
        action = "run"
        if skip_ok and cp.finished_ok(rd):
            want = _requested(spec, n, overrides)
            have = json.loads((rd / "input" / "case.json").read_text())["params"]
            bad = [f"{k}: run has {have.get(k)}, requested {want[k]}" for k in SKIP_KEYS
                   if have.get(k) != want[k]]
            action = ("refuse: " + "; ".join(bad)) if bad else "skip (already OK)"
        cases.append({"case": n, "run_dir": str(rd), "t_end_h": p.get("t_end_h"),
                      "forced_h": p.get("forced_h"), "deltaT": p.get("deltaT"),
                      "stages": stage_plan(p), "action": action})
    up = cp.build_up_to_date(cfg_dir, build_dir, np_ > 1)
    if not any(c["action"] == "run" for c in cases):
        b = "none (nothing to run)"
    elif skip_ok and up:
        b = "none (up to date)"
    else:
        b = "build"
    return {"config": config, "np": np_, "cases": cases,
            "build": {"dir": str(build_dir), "up_to_date": up, "action": b}}


def run_campaign(config: str, pattern: str, np_: int, *, max_concurrent: int = 1,
                 runs_root: Path = EXP4_RUNS, build_root: Path = EXP4_BUILDS,
                 config_root: Path | None = None, cases_file: Path | None = None,
                 overrides: dict | None = None, run_suffix: str = "",
                 sh: Callable[[list], int] = _sh, pgrep: Callable[[], str] | None = None,
                 skip_ok: bool = False, disk_usage=None) -> dict[str, str]:
    """Build ``config`` once, then generate and run the selected cases. Returns {case: state}."""
    cp.check_concurrency(np_, max_concurrent)
    spec = load_cases(cases_file)
    names = cp.select_cases(spec["cases"], config, pattern)
    overrides = cp.check_overrides(names, overrides, spec)
    busy = cp.other_mitgcm_processes(pgrep)
    if busy:
        raise RuntimeError("another MPI / model process is running, refusing to start: "
                           + " | ".join(busy))
    cfg_dir = Path(config_root or PKG / "config") / config
    cp.check_np(cfg_dir / "code" / "SIZE.h", np_)
    build_dir = Path(build_root) / config
    run_dirs = {n: Path(runs_root) / f"{n}{run_suffix}" for n in names}

    done: set[str] = set()
    if skip_ok:
        for n in names:
            if not cp.finished_ok(run_dirs[n]):
                continue
            want = _requested(spec, n, overrides)
            have = json.loads((run_dirs[n] / "input" / "case.json").read_text())["params"]
            bad = [f"{k}: run has {have.get(k)}, requested {want[k]}" for k in SKIP_KEYS
                   if have.get(k) != want[k]]
            if bad:
                raise RuntimeError(f"--skip-ok: {run_dirs[n]} is OK but was run with other "
                                   "parameters (" + "; ".join(bad) + "); move it away first")
            done.add(n)
    todo = [n for n in names if n not in done]

    inputs, plans, stems = {}, {}, {}
    for n in todo:
        inp = run_dirs[n] / "input"
        meta = make_case(n, inp, cases_file=cases_file, overrides=overrides)
        cp.check_size(inp, cfg_dir / "code" / "SIZE.h")
        inputs[n], plans[n] = inp, [tuple(s) for s in meta["actual"]["stages"]]
        # required restart files: the case's pickup_stems (fjord ice cases add pickup_seaice)
        stems[n] = tuple(meta["params"].get("pickup_stems")
                         or spec["configs"][config].get("pickup_stems", ["pickup"]))
    if todo:
        cp.check_free_space(Path(runs_root), list(inputs.values()), disk_usage)
        if not (skip_ok and cp.build_up_to_date(cfg_dir, build_dir, np_ > 1)):
            if sh([BUILD_SH, cfg_dir, build_dir] + (["--mpi"] if np_ > 1 else [])) != 0:
                raise RuntimeError(f"build of {config} failed")

    def run_one(n: str) -> str:
        record_binary(inputs[n], build_dir)
        plan = plans[n]
        texts = {1: (inputs[n] / "data").read_text()}
        if len(plan) > 1:
            texts.update({k: (inputs[n] / "data.free").read_text() for k in range(2, len(plan) + 1)})
        print(f"[run_campaign] {n}: running in {run_dirs[n]} (stages {plan})", flush=True)
        st = cp.run_stages(run_dirs[n], inputs[n], build_dir, np_, len(plan), sh, RUN_SH,
                           pickup_stems=stems[n], plan=plan, stage_data=texts.__getitem__)
        print(f"[run_campaign] {n}: {st}", flush=True)
        return st

    results = {n: "OK" for n in done}
    for n in done:
        print(f"[run_campaign] {n}: already OK in {run_dirs[n]}, skipped (--skip-ok)", flush=True)
    results.update(cp.run_pool(todo, np_, max_concurrent, run_one))
    left = cp.other_mitgcm_processes(pgrep)
    if left:
        raise RuntimeError("processes left after the campaign: " + " | ".join(left))
    return {n: results[n] for n in names}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config", required=True)
    ap.add_argument("--cases", required=True, help="fnmatch glob over case names")
    ap.add_argument("--np", type=int, default=4, dest="np_")
    ap.add_argument("--max-concurrent", type=int, default=1)
    ap.add_argument("--end-time", type=float, default=None, help="run length [s] (sets t_end_h)")
    ap.add_argument("--run-suffix", default="", help="appended to each run directory name")
    ap.add_argument("--runs-root", type=Path, default=EXP4_RUNS)
    ap.add_argument("--build-root", type=Path, default=EXP4_BUILDS)
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE",
                    help="override a numeric case parameter (repeatable)")
    ap.add_argument("--dry-run", action="store_true", help="list the cases and exit")
    ap.add_argument("--skip-ok", action="store_true",
                    help="do not rerun cases already OK (same deltaT/forced_h/t_end_h/edits)")
    a = ap.parse_args(argv)
    ov = cp.parse_sets(a.set)
    if a.end_time is not None:
        ov["t_end_h"] = a.end_time / 3600.0
    if a.dry_run:
        # case names on stdout (as before); the plan on stderr
        print("\n".join(cp.select_cases(load_cases()["cases"], a.config, a.cases)))
        pl = plan_campaign(a.config, a.cases, a.np_, overrides=ov or None, run_suffix=a.run_suffix,
                           runs_root=a.runs_root, build_root=a.build_root, skip_ok=a.skip_ok)
        for c in pl["cases"]:
            print(f"[dry-run] {c['case']}: {c['run_dir']} t_end_h {c['t_end_h']} forced_h "
                  f"{c['forced_h']} deltaT {c['deltaT']} stages {c['stages']} -> {c['action']}",
                  file=sys.stderr)
        b = pl["build"]
        print(f"[dry-run] build: {b['dir']} up_to_date={b['up_to_date']} -> {b['action']}",
              file=sys.stderr)
        return 0
    res = run_campaign(a.config, a.cases, a.np_, max_concurrent=a.max_concurrent,
                       runs_root=a.runs_root, build_root=a.build_root,
                       overrides=ov or None, run_suffix=a.run_suffix, skip_ok=a.skip_ok)
    print(json.dumps(res, indent=2))
    return 0 if all(s == "OK" for s in res.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
