#!/opt/anaconda3/envs/pyocean/bin/python
"""Run a campaign of Exp. 2 (ISOMIP+ cavity) MITgcm cases: build once, then run the cases.

Usage::

    run_campaign.py --config ocean0_4km --cases '<glob>' [--np 1|5] [--max-concurrent K]
                    [--stages N] [--end-time S] [--run-suffix _short] [--set KEY=VALUE]
                    [--skip-ok] [--dry-run]

For each case of ``--config`` matching ``<glob>`` (fnmatch over cases.yaml names, ensemble
expanded; registry order) the inputs are generated by ``gendata.make_case`` in
``<runs_root>/<case><suffix>/input/`` and run with ``scripts/run_mitgcm.sh``. The build
(``scripts/build_mitgcm.sh``, ``--mpi`` if np > 1) goes to ``<build_root>/<config>/`` and
happens once, before the first run.

Resource rules (global constraints): either up to 5 serial runs at a time (``--np 1
--max-concurrent K``, K <= 5) or one run on 5 MPI ranks (``--np 5``, K = 1); anything else
is refused, and np must equal nPx * nPy of the config's SIZE.h. The campaign refuses to
start while any MPI launcher or model process runs
(matched by process name), and fails if one is left behind at the end. SIZE.h (Nx, Ny, Nr)
is checked against every generated grid, and the run disk must have room for all inputs.

``--stages N`` chains N equal restart stages per case (pfcommon.campaign.run_stages):
stage k restarts from stage k-1's last pickup, inputs and pickups copied, never linked.
Every case gets ``run_status_final.json``.

``--skip-ok`` does not rerun a case whose run directory is already OK, provided its
recorded deltaT, endTime, gammaT and melt_law equal the requested ones (otherwise the
campaign refuses to start: an OK run made with the void pre-R21 u* law, which has no
melt_law in its case.json, is never reused nor overwritten); the build is skipped when it is up to date. ``--set KEY=VALUE``
overrides a numeric case parameter (e.g. ``gammaT`` before calibration); ``--end-time``
overrides endTime. The exit code is 1 if any case is not OK.

``--run-suffix`` defaults to ``_r21`` (R21): every Exp. 2 production run directory carries
it, so the void runs without suffix are never a target. An explicit suffix replaces it.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Callable

PKG = Path(__file__).resolve().parents[1]          # exp2_isomip_cavity/
REPO = PKG.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from pfcommon import campaign as cp  # noqa: E402
from pfcommon.paths import EXP2_BUILDS, EXP2_RUNS  # noqa: E402
from exp2_isomip_cavity.gendata.make_case import load_cases, make_case  # noqa: E402

BUILD_SH = REPO / "scripts" / "build_mitgcm.sh"
RUN_SH = REPO / "scripts" / "run_mitgcm.sh"
THREAD_ENV = {"OPENBLAS_NUM_THREADS": "1", "OMP_NUM_THREADS": "1", "VECLIB_MAXIMUM_THREADS": "1"}
SKIP_KEYS = ("deltaT", "endTime", "gammaT", "melt_law")   # must match for --skip-ok reuse
DEFAULT_RUN_SUFFIX = "_r21"          # R21: production run directories (see docstring)


def _sh(cmd: list) -> int:
    env = {**os.environ, **THREAD_ENV}
    return subprocess.run([str(c) for c in cmd], env=env).returncode


def _requested(spec: dict, name: str, overrides: dict | None) -> dict:
    case = spec["cases"][name]
    p = {**spec["configs"][case["config"]], **case, **(overrides or {})}
    return {k: p.get(k) for k in SKIP_KEYS}


def run_campaign(config: str, pattern: str, np_: int, *, max_concurrent: int = 1,
                 n_stages: int = 1, runs_root: Path = EXP2_RUNS, build_root: Path = EXP2_BUILDS,
                 config_root: Path | None = None, cases_file: Path | None = None,
                 template_dir: Path | None = None, geom_path: Path | None = None,
                 overrides: dict | None = None, run_suffix: str = "",
                 sh: Callable[[list], int] = _sh, pgrep: Callable[[], str] | None = None,
                 skip_ok: bool = False, disk_usage=None) -> dict[str, str]:
    """Build ``config`` once, then generate and run the selected cases, at most
    ``max_concurrent`` at a time. Returns {case: state}."""
    cp.check_concurrency(np_, max_concurrent)
    spec = load_cases(cases_file)
    names = cp.select_cases(spec["cases"], config, pattern)
    overrides = cp.check_overrides(names, overrides, spec)
    busy = cp.other_mitgcm_processes(pgrep)
    if busy:
        raise RuntimeError("another MPI / model process is running, refusing to start: "
                           + " | ".join(busy))
    cfg_dir = Path(config_root or PKG / "config") / config
    cp.check_np(cfg_dir / "code" / "SIZE.h", np_)
    build_dir = Path(build_root) / config
    run_dirs = {n: Path(runs_root) / f"{n}{run_suffix}" for n in names}

    done: set[str] = set()
    if skip_ok:
        for n in names:
            if not cp.finished_ok(run_dirs[n]):
                continue
            want = _requested(spec, n, overrides)
            have = json.loads((run_dirs[n] / "input" / "case.json").read_text())["params"]
            bad = [f"{k}: run has {have.get(k)}, requested {want[k]}" for k in SKIP_KEYS
                   if have.get(k) != want[k]]
            if bad:
                void = " (no melt_law: void pre-R21 u* law, R21)" if not have.get("melt_law") else ""
                raise RuntimeError(f"--skip-ok: {run_dirs[n]} is OK but was run with other "
                                   "parameters (" + "; ".join(bad) + f"){void}; move it away "
                                   "first")
            done.add(n)
    todo = [n for n in names if n not in done]

    # inputs first (cheap, and every check happens before the model starts)
    inputs = {}
    for n in todo:
        inp = run_dirs[n] / "input"
        make_case(n, inp, template_dir=template_dir, cases_file=cases_file,
                  overrides=overrides, geom_path=geom_path)
        cp.check_size(inp, cfg_dir / "code" / "SIZE.h")
        inputs[n] = inp
    if todo:
        cp.check_free_space(Path(runs_root), list(inputs.values()), disk_usage)
        if not (skip_ok and cp.build_up_to_date(cfg_dir, build_dir, np_ > 1)):
            if sh([BUILD_SH, cfg_dir, build_dir] + (["--mpi"] if np_ > 1 else [])) != 0:
                raise RuntimeError(f"build of {config} failed")

    pickup_stems = tuple(spec["configs"][config].get("pickup_stems", ["pickup"]))

    def run_one(n: str) -> str:
        print(f"[run_campaign] {n}: running in {run_dirs[n]} ({n_stages} stage(s))", flush=True)
        st = cp.run_stages(run_dirs[n], inputs[n], build_dir, np_, n_stages, sh, RUN_SH,
                           pickup_stems=pickup_stems)
        print(f"[run_campaign] {n}: {st}", flush=True)
        return st

    results = {n: "OK" for n in done}
    for n in done:
        print(f"[run_campaign] {n}: already OK in {run_dirs[n]}, skipped (--skip-ok)", flush=True)
    results.update(cp.run_pool(todo, np_, max_concurrent, run_one))
    left = cp.other_mitgcm_processes(pgrep)
    if left:
        raise RuntimeError("processes left after the campaign: " + " | ".join(left))
    return {n: results[n] for n in names}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config", required=True)
    ap.add_argument("--cases", required=True, help="fnmatch glob over case names")
    ap.add_argument("--np", type=int, default=1, dest="np_")
    ap.add_argument("--max-concurrent", type=int, default=1)
    ap.add_argument("--stages", type=int, default=1, help="chained restart stages per case")
    ap.add_argument("--end-time", type=float, default=None, help="override endTime [s]")
    ap.add_argument("--run-suffix", default=DEFAULT_RUN_SUFFIX,
                    help="appended to each run directory name (default _r21, R21)")
    ap.add_argument("--runs-root", type=Path, default=EXP2_RUNS)
    ap.add_argument("--build-root", type=Path, default=EXP2_BUILDS)
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE",
                    help="override a numeric case parameter (repeatable)")
    ap.add_argument("--dry-run", action="store_true", help="list the cases and exit")
    ap.add_argument("--skip-ok", action="store_true",
                    help="do not rerun cases already OK (same deltaT/endTime/gammaT/melt_law)")
    a = ap.parse_args(argv)
    if a.dry_run:
        print("\n".join(cp.select_cases(load_cases()["cases"], a.config, a.cases)))
        return 0
    ov = cp.parse_sets(a.set)
    if a.end_time is not None:
        ov["endTime"] = a.end_time
    res = run_campaign(a.config, a.cases, a.np_, max_concurrent=a.max_concurrent,
                       n_stages=a.stages, runs_root=a.runs_root, build_root=a.build_root,
                       overrides=ov or None, run_suffix=a.run_suffix, skip_ok=a.skip_ok)
    print(json.dumps(res, indent=2))
    return 0 if all(s == "OK" for s in res.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
