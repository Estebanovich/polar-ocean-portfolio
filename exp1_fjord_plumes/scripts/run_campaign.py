#!/opt/anaconda3/envs/pyocean/bin/python
"""Run a campaign of Exp. 1 MITgcm cases: build once, then run the cases in series.

Usage::

    run_campaign.py --config a_line2d --cases '<glob>' --np N
                    [--end-time S] [--run-suffix _short2h] [--dry-run]

For each case matching ``<glob>`` (fnmatch over the case names of
``cases.yaml`` that belong to ``--config``; cases.yaml order) the inputs are
generated by ``gendata.make_case`` in ``<runs_root>/<case><suffix>/input/``
and run with ``scripts/run_mitgcm.sh`` in ``<runs_root>/<case><suffix>/``.
The build (``scripts/build_mitgcm.sh``, ``--mpi`` if N > 1) goes to
``<build_root>/<config>/`` and happens once, before the first run.

Resource rules (global constraints): N <= 5 MPI processes; one heavy run at a
time, so the campaign refuses to start if ``pgrep -fl "mpirun|mitgcmuv"``
finds anything, and stops if a run leaves a process behind. Before running a
case, SIZE.h (Nx, Ny, Nr) is checked against the generated grid.

``--end-time`` overrides ``endTime`` (e.g. 7200 for the timed 2 h short run of
Task 4; nTimeSteps is derived from it by make_case). A FAILED case is reported
and the series continues; the exit code is 1 if any case is not OK.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Callable

PKG = Path(__file__).resolve().parents[1]          # exp1_fjord_plumes/
REPO = PKG.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from exp1_fjord_plumes.gendata.make_case import load_cases, make_case  # noqa: E402

RUNS_ROOT = Path("/Volumes/LaCie/portfolio_runs/exp1")
BUILD_ROOT = Path("/Volumes/ESTEBAN_MIT/portfolio_builds/exp1")
BUILD_SH = REPO / "scripts" / "build_mitgcm.sh"
RUN_SH = REPO / "scripts" / "run_mitgcm.sh"
MAX_NP = 5
THREAD_ENV = {"OPENBLAS_NUM_THREADS": "1", "OMP_NUM_THREADS": "1", "VECLIB_MAXIMUM_THREADS": "1"}


def select_cases(config: str, pattern: str, cases_file: Path | None = None) -> list[str]:
    """Case names of ``config`` matching the fnmatch ``pattern``, in cases.yaml order.

    Raises ValueError if nothing matches; the message names matching cases
    of other configurations, if any.
    """
    cases = load_cases(cases_file)["cases"]
    hits = [n for n in cases if fnmatch.fnmatchcase(n, pattern)]
    mine = [n for n in hits if cases[n]["config"] == config]
    if not mine:
        other = [n for n in hits if n not in mine]
        extra = f" (matches of other configs: {', '.join(other)})" if other else ""
        raise ValueError(f"no case of config {config!r} matches {pattern!r}{extra}")
    return mine


def _pgrep() -> str:
    r = subprocess.run(["pgrep", "-fl", "mpirun|mitgcmuv"], capture_output=True, text=True)
    return r.stdout


def other_mitgcm_processes(pgrep: Callable[[], str] | None = None) -> list[str]:
    """Lines of ``pgrep -fl "mpirun|mitgcmuv"``, minus this process."""
    out = (pgrep or _pgrep)()
    me = str(os.getpid())
    return [ln.strip() for ln in out.splitlines()
            if ln.strip() and ln.split()[0] != me]


def _size_param(text: str, name: str) -> int:
    m = re.search(rf"^\s*&?\s*{name}\s*=\s*(\d+)", text, re.MULTILINE)
    if not m:
        raise RuntimeError(f"SIZE.h: cannot find {name}")
    return int(m.group(1))


def check_size(case_dir: Path, size_h: Path) -> None:
    """Raise RuntimeError unless SIZE.h (sNx nSx nPx, sNy nSy nPy, Nr) matches case.json."""
    p = json.loads((Path(case_dir) / "case.json").read_text())["params"]
    t = Path(size_h).read_text()
    Nx = _size_param(t, "sNx") * _size_param(t, "nSx") * _size_param(t, "nPx")
    Ny = _size_param(t, "sNy") * _size_param(t, "nSy") * _size_param(t, "nPy")
    Nr = _size_param(t, "Nr")
    bad = [f"{k}: SIZE.h {s} != grid {g}" for k, s, g in
           (("Nx", Nx, p["nx"]), ("Ny", Ny, p["ny"]), ("Nr", Nr, p["nz"])) if s != g]
    if bad:
        raise RuntimeError(f"{size_h} does not match {case_dir}: " + "; ".join(bad))


def _sh(cmd: list) -> int:
    env = {**os.environ, **THREAD_ENV}
    return subprocess.run([str(c) for c in cmd], env=env).returncode


def run_campaign(config: str, pattern: str, np_: int, *,
                 runs_root: Path = RUNS_ROOT, build_root: Path = BUILD_ROOT,
                 cases_file: Path | None = None, overrides: dict | None = None,
                 run_suffix: str = "", sh: Callable[[list], int] = _sh,
                 pgrep: Callable[[], str] | None = None) -> dict[str, str]:
    """Build ``config`` once, then generate and run each selected case in series.

    Returns {case: state} with state from run_status.json (OK / FAILED) or
    "NO_STATUS". Raises RuntimeError before doing anything if another
    MITgcm is running, or if the build fails.
    """
    if not 1 <= np_ <= MAX_NP:
        raise ValueError(f"np={np_} outside 1..{MAX_NP} (global constraint: <= 5 MPI procs)")
    names = select_cases(config, pattern, cases_file)
    busy = other_mitgcm_processes(pgrep)
    if busy:
        raise RuntimeError("another mpirun/mitgcmuv is running, refusing to start: "
                           + " | ".join(busy))
    cfg_dir = PKG / "config" / config
    build_dir = Path(build_root) / config
    cmd = [BUILD_SH, cfg_dir, build_dir] + (["--mpi"] if np_ > 1 else [])
    if sh(cmd) != 0:
        raise RuntimeError(f"build of {config} failed")
    results: dict[str, str] = {}
    for name in names:
        run_dir = Path(runs_root) / f"{name}{run_suffix}"
        inp = make_case(name, run_dir / "input", cases_file=cases_file, overrides=overrides)
        check_size(inp, cfg_dir / "code" / "SIZE.h")
        print(f"[run_campaign] {name}: running in {run_dir}", flush=True)
        sh([RUN_SH, build_dir, inp, run_dir, np_])
        st_file = run_dir / "run_status.json"
        results[name] = (json.loads(st_file.read_text()).get("state", "NO_STATUS")
                         if st_file.exists() else "NO_STATUS")
        print(f"[run_campaign] {name}: {results[name]}", flush=True)
        left = other_mitgcm_processes(pgrep)
        if left:
            raise RuntimeError(f"processes left after {name}: " + " | ".join(left))
    return results


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config", required=True)
    ap.add_argument("--cases", required=True, help="fnmatch glob over case names")
    ap.add_argument("--np", type=int, default=1, dest="np_")
    ap.add_argument("--end-time", type=float, default=None, help="override endTime [s]")
    ap.add_argument("--run-suffix", default="", help="appended to each run directory name")
    ap.add_argument("--runs-root", type=Path, default=RUNS_ROOT)
    ap.add_argument("--build-root", type=Path, default=BUILD_ROOT)
    ap.add_argument("--dry-run", action="store_true", help="list the cases and exit")
    a = ap.parse_args(argv)
    if a.dry_run:
        print("\n".join(select_cases(a.config, a.cases)))
        return 0
    ov = {"endTime": a.end_time} if a.end_time is not None else None
    res = run_campaign(a.config, a.cases, a.np_, runs_root=a.runs_root,
                       build_root=a.build_root, overrides=ov, run_suffix=a.run_suffix)
    print(json.dumps(res, indent=2))
    return 0 if all(s == "OK" for s in res.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
