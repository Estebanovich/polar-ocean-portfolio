#!/opt/anaconda3/envs/pyocean/bin/python
"""Run a campaign of Exp. 1 MITgcm cases: build once, then run the cases in series.

Usage::

    run_campaign.py --config a_line2d --cases '<glob>' --np N
                    [--end-time S] [--run-suffix _short2h] [--dry-run]

For each case matching ``<glob>`` (fnmatch over the case names of
``cases.yaml`` that belong to ``--config``; cases.yaml order) the inputs are
generated by ``gendata.make_case`` in ``<runs_root>/<case><suffix>/input/``
and run with ``scripts/run_mitgcm.sh`` in ``<runs_root>/<case><suffix>/``.
The build (``scripts/build_mitgcm.sh``, ``--mpi`` if N > 1) goes to
``<build_root>/<config>/`` and happens once, before the first run.

Resource rules (global constraints): N <= 5 MPI processes; one heavy run at a
time, so the campaign refuses to start if ``pgrep -fl "mpirun|mitgcmuv"``
finds anything, and stops if a run leaves a process behind. Before running a
case, SIZE.h (Nx, Ny, Nr) is checked against the generated grid.

``--skip-ok`` resumes a campaign (R30: run the first case, gate it with
``b_gate.py``, then the rest): a case whose run directory already holds a
run_status.json with state OK (and last_iter >= n_timesteps) is not run again,
provided its recorded deltaT/endTime equal the ones requested (otherwise the
campaign refuses to start), and the build is skipped when ``mitgcmuv`` is newer
than every file in ``config/<cfg>/code`` and its Makefile matches the MPI
choice (``-DALLOW_USE_MPI`` iff N > 1).

Two-stage cases (config (c) wind cases: make_case writes ``data.stage2``,
thesis protocol, verification/BayIW_Rectan/README.md): stage 1 runs in
``<run_dir>``; if it is OK and the pickups of its last iteration exist
(``pickup.<n1>.data/.meta`` AND the OB pickup of the active scheme, derived
from the case's ``data.obcs``: ``pickup_stevensE.<n1>.*`` if ``useStevensEast``
-- (c) now uses Stevens, pkg/obcs/obcs_write_pickup.F:225-231, read back at
obcs_read_pickup.F:241-246 -- or ``pickup_orlanskiE.<n1>.*`` if
``useOrlanskiEast`` (the C3 lesson of (a): the restart is bit-exact only with
the OB pickup); N/S/W analogues likewise), they are
COPIED (never linked: LaCie is exFAT) with the inputs into
``<run_dir>/input_stage2`` (``data.stage2`` -> ``data``) and stage 2 runs in
``<run_dir>/stage2``. Each stage keeps its own run_status.json; every case
gets ``<run_dir>/run_status_final.json``, state OK only if all stages are OK
and the last iteration equals nIter0 + nTimeSteps of the last stage.
``--set KEY=VALUE`` overrides any numeric case parameter (e.g.
``wind_stage1_s=43200`` so that a 1-day timed run has both stages).

``--end-time`` overrides ``endTime`` (e.g. 7200 for the timed 2 h short run of
Task 4; nTimeSteps is derived from it by make_case). A FAILED case is reported
and the series continues; the exit code is 1 if any case is not OK.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Callable

PKG = Path(__file__).resolve().parents[1]          # exp1_fjord_plumes/
REPO = PKG.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from exp1_fjord_plumes.gendata.make_case import (  # noqa: E402
    STAGE2_NAME, is_two_stage, load_cases, make_case)

RUNS_ROOT = Path("/Volumes/LaCie/portfolio_runs/exp1")
BUILD_ROOT = Path("/Volumes/ESTEBAN_MIT/portfolio_builds/exp1")
BUILD_SH = REPO / "scripts" / "build_mitgcm.sh"
RUN_SH = REPO / "scripts" / "run_mitgcm.sh"
MAX_NP = 5
THREAD_ENV = {"OPENBLAS_NUM_THREADS": "1", "OMP_NUM_THREADS": "1", "VECLIB_MAXIMUM_THREADS": "1"}


def select_cases(config: str, pattern: str, cases_file: Path | None = None) -> list[str]:
    """Case names of ``config`` matching the fnmatch ``pattern``, in cases.yaml order.

    Raises ValueError if nothing matches; the message names matching cases
    of other configurations, if any.
    """
    cases = load_cases(cases_file)["cases"]
    hits = [n for n in cases if fnmatch.fnmatchcase(n, pattern)]
    mine = [n for n in hits if cases[n]["config"] == config]
    if not mine:
        other = [n for n in hits if n not in mine]
        extra = f" (matches of other configs: {', '.join(other)})" if other else ""
        raise ValueError(f"no case of config {config!r} matches {pattern!r}{extra}")
    return mine


# Match the process *name* only (no -f): with -f, any shell whose command line
# merely mentions the binary (an editor, a log grep) was taken for a model run.
PROC_PATTERN = "^(mpirun|mpiexec|orterun|prterun|mitgcmuv)$"


def _pgrep() -> str:
    r = subprocess.run(["pgrep", "-l", PROC_PATTERN], capture_output=True, text=True)
    return r.stdout


def other_mitgcm_processes(pgrep: Callable[[], str] | None = None) -> list[str]:
    """Lines of ``pgrep -fl "mpirun|mitgcmuv"``, minus this process."""
    out = (pgrep or _pgrep)()
    me = str(os.getpid())
    return [ln.strip() for ln in out.splitlines()
            if ln.strip() and ln.split()[0] != me]


def _size_param(text: str, name: str) -> int:
    m = re.search(rf"^\s*&?\s*{name}\s*=\s*(\d+)", text, re.MULTILINE)
    if not m:
        raise RuntimeError(f"SIZE.h: cannot find {name}")
    return int(m.group(1))


def check_size(case_dir: Path, size_h: Path) -> None:
    """Raise RuntimeError unless SIZE.h (sNx nSx nPx, sNy nSy nPy, Nr) matches case.json."""
    p = json.loads((Path(case_dir) / "case.json").read_text())["params"]
    t = Path(size_h).read_text()
    Nx = _size_param(t, "sNx") * _size_param(t, "nSx") * _size_param(t, "nPx")
    Ny = _size_param(t, "sNy") * _size_param(t, "nSy") * _size_param(t, "nPy")
    Nr = _size_param(t, "Nr")
    bad = [f"{k}: SIZE.h {s} != grid {g}" for k, s, g in
           (("Nx", Nx, p["nx"]), ("Ny", Ny, p["ny"]), ("Nr", Nr, p["nz"])) if s != g]
    if bad:
        raise RuntimeError(f"{size_h} does not match {case_dir}: " + "; ".join(bad))


SKIP_KEYS = ("deltaT", "endTime")  # must match for --skip-ok to reuse an OK run


def finished_ok(run_dir: Path) -> bool:
    """True if the run says OK and the last time step was reached; for a
    two-stage case (input/data.stage2) only run_status_final.json counts."""
    run_dir = Path(run_dir)
    f = run_dir / "run_status.json"
    if is_two_stage(run_dir / "input"):
        f = run_dir / "run_status_final.json"
    try:
        st = json.loads(f.read_text())
    except (OSError, json.JSONDecodeError):
        return False
    if f.name == "run_status_final.json":
        return st.get("state") == "OK" and st.get("last_iter") == st.get("expected_last_iter")
    return st.get("state") == "OK" and st.get("last_iter", -1) >= st.get("n_timesteps", 1 << 62)


def parse_sets(items: list[str] | None) -> dict:
    """['KEY=VALUE', ...] -> {KEY: int or float} (``--set``); integer literals
    stay int (types are reconciled per case by ``check_overrides``)."""
    out = {}
    for it in items or []:
        if "=" not in it:
            raise ValueError(f"--set expects KEY=VALUE, got {it!r}")
        k, v = (x.strip() for x in it.split("=", 1))
        try:
            out[k] = int(v)
        except ValueError:
            out[k] = float(v)
    return out


def check_overrides(names: list[str], overrides: dict | None,
                    cases_file: Path | None = None) -> dict:
    """Reject keys absent from the merged parameters of any selected case and
    give each value the type of the parameter it replaces (int stays int;
    a non-integral value for an int parameter is an error)."""
    if not overrides:
        return overrides or {}
    spec = load_cases(cases_file)
    out = dict(overrides)
    for name in names:
        case = spec["cases"][name]
        merged = {**spec["configs"][case["config"]], **case}
        for k, v in overrides.items():
            if k not in merged:
                raise ValueError(f"--set {k}: not a parameter of case {name}")
            if isinstance(merged[k], bool) or not isinstance(merged[k], (int, float)):
                raise ValueError(f"--set {k}: parameter is not numeric")
            if isinstance(merged[k], int):
                if float(v) != int(float(v)):
                    raise ValueError(f"--set {k}={v}: integer parameter")
                out[k] = int(v)
            else:
                out[k] = float(v)
    return out


def _status(run_dir: Path) -> dict | None:
    f = Path(run_dir) / "run_status.json"
    try:
        return json.loads(f.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def _nml_int(text: str, key: str) -> int:
    for ln in text.splitlines():
        if ln.lstrip().startswith("#"):
            continue
        m = re.match(rf"\s*{key}\s*=\s*(\d+)", ln, re.IGNORECASE)
        if m:
            return int(m.group(1))
    raise RuntimeError(f"{key} not found")


def _write_final(run_dir: Path, state: str, stages: dict, expected: int | None,
                 reason: str | None = None) -> str:
    last = [st for st in stages.values() if st]
    fin = {"state": state, "last_iter": last[-1].get("last_iter") if last else None,
           "expected_last_iter": expected, "stages": stages}
    if reason:
        fin["reason"] = reason
    (Path(run_dir) / "run_status_final.json").write_text(json.dumps(fin, indent=2))
    return state


def required_ob_pickups(inp: Path) -> list[str]:
    """OB pickup stems that the active OB schemes of ``inp/data.obcs`` write.

    pkg/obcs/obcs_write_pickup.F writes ``pickup_orlanskiE.<iter>`` if
    useOrlanskiEast (and N/S/W analogues, lines 37-195) and
    ``pickup_stevensE.<iter>`` if useStevensEast (lines 225-231); the
    restart reads them back (obcs_read_pickup.F:132-157, 241-246). Comment
    lines and ``.FALSE.`` flags do not count.
    """
    live = "\n".join(l.split("#")[0] for l in (Path(inp) / "data.obcs").read_text().splitlines())
    out = []
    for scheme in ("orlanski", "stevens"):
        for side in ("North", "South", "East", "West"):
            if re.search(rf"\buse{scheme}{side}\s*=\s*\.TRUE\.", live, re.IGNORECASE):
                out.append(f"pickup_{scheme}{side[0]}")
    return out


def run_stage2(run_dir: Path, inp: Path, build_dir: Path, np_: int,
               sh: Callable[[list], int]) -> str:
    """Stage 2 of a two-stage case (module docstring). Returns the final state."""
    import shutil
    run_dir, inp = Path(run_dir), Path(inp)
    st1 = _status(run_dir)
    s2_text = (inp / STAGE2_NAME).read_text()
    n1, n2 = _nml_int(s2_text, "nIter0"), _nml_int(s2_text, "nTimeSteps")
    stages = {"1": st1, "2": None}
    if not (st1 and st1.get("state") == "OK" and st1.get("last_iter") == n1):
        return _write_final(run_dir, "FAILED", stages, n1 + n2,
                            f"stage 1 not OK or did not reach iteration {n1}")
    tag = f"{n1:010d}"
    pick = sorted(run_dir.glob(f"pickup*.{tag}*"))
    names = {f.name for f in pick}
    missing = [f for f in (f"pickup.{tag}.data", f"pickup.{tag}.meta") if f not in names]
    for stem in required_ob_pickups(inp):
        if not any(n.startswith(f"{stem}.{tag}") for n in names):
            missing.append(f"{stem}.{tag}.* (OB pickup of the active scheme)")
    if missing:
        return _write_final(run_dir, "FAILED", stages, n1 + n2,
                            "missing stage-1 pickup: " + ", ".join(missing))
    inp2 = run_dir / "input_stage2"
    if inp2.exists():
        shutil.rmtree(inp2)
    shutil.copytree(inp, inp2, symlinks=False)          # copies, never links
    (inp2 / "data").write_text(s2_text)
    (inp2 / STAGE2_NAME).unlink()
    for f in pick:
        shutil.copyfile(f, inp2 / f.name)                # content copy (follows links)
    sh([RUN_SH, build_dir, inp2, run_dir / "stage2", np_])
    st2 = _status(run_dir / "stage2")
    stages["2"] = st2
    ok = bool(st2 and st2.get("state") == "OK" and st2.get("last_iter") == n1 + n2)
    return _write_final(run_dir, "OK" if ok else "FAILED", stages, n1 + n2,
                        None if ok else "stage 2 not OK or wrong last iteration")


def _requested(name: str, overrides: dict | None, cases_file: Path | None) -> dict:
    spec = load_cases(cases_file)
    case = spec["cases"][name]
    p = {**spec["configs"][case["config"]], **case, **(overrides or {})}
    return {k: p[k] for k in SKIP_KEYS}


def build_up_to_date(cfg_dir: Path, build_dir: Path, mpi: bool) -> bool:
    """mitgcmuv newer than every file in cfg_dir/code, and built with/without MPI as asked."""
    exe, mk = Path(build_dir) / "mitgcmuv", Path(build_dir) / "Makefile"
    if not (exe.exists() and mk.exists()):
        return False
    if ("-DALLOW_USE_MPI" in mk.read_text()) != mpi:
        return False
    newest = max(f.stat().st_mtime for f in (Path(cfg_dir) / "code").iterdir() if f.is_file())
    return exe.stat().st_mtime > newest


def _sh(cmd: list) -> int:
    env = {**os.environ, **THREAD_ENV}
    return subprocess.run([str(c) for c in cmd], env=env).returncode


def run_campaign(config: str, pattern: str, np_: int, *,
                 runs_root: Path = RUNS_ROOT, build_root: Path = BUILD_ROOT,
                 cases_file: Path | None = None, overrides: dict | None = None,
                 run_suffix: str = "", sh: Callable[[list], int] = _sh,
                 pgrep: Callable[[], str] | None = None, skip_ok: bool = False) -> dict[str, str]:
    """Build ``config`` once, then generate and run each selected case in series.

    Returns {case: state} with state from run_status.json (OK / FAILED) or
    "NO_STATUS". Raises RuntimeError before doing anything if another
    MITgcm is running, or if the build fails.
    """
    if not 1 <= np_ <= MAX_NP:
        raise ValueError(f"np={np_} outside 1..{MAX_NP} (global constraint: <= 5 MPI procs)")
    names = select_cases(config, pattern, cases_file)
    overrides = check_overrides(names, overrides, cases_file)
    busy = other_mitgcm_processes(pgrep)
    if busy:
        raise RuntimeError("another mpirun/mitgcmuv is running, refusing to start: "
                           + " | ".join(busy))
    cfg_dir = PKG / "config" / config
    build_dir = Path(build_root) / config
    done: set[str] = set()
    if skip_ok:
        for name in names:
            run_dir = Path(runs_root) / f"{name}{run_suffix}"
            if not finished_ok(run_dir):
                continue
            want = _requested(name, overrides, cases_file)
            have = json.loads((run_dir / "input" / "case.json").read_text())["params"]
            bad = [f"{k}: run has {have.get(k)}, requested {want[k]}" for k in SKIP_KEYS
                   if have.get(k) != want[k]]
            if bad:
                raise RuntimeError(f"--skip-ok: {run_dir} is OK but was run with other "
                                   "parameters (" + "; ".join(bad) + "); move it away first")
            done.add(name)
    todo = [n for n in names if n not in done]
    if todo and not (skip_ok and build_up_to_date(cfg_dir, build_dir, np_ > 1)):
        cmd = [BUILD_SH, cfg_dir, build_dir] + (["--mpi"] if np_ > 1 else [])
        if sh(cmd) != 0:
            raise RuntimeError(f"build of {config} failed")
    results: dict[str, str] = {}
    for name in names:
        run_dir = Path(runs_root) / f"{name}{run_suffix}"
        if name in done:
            results[name] = "OK"
            print(f"[run_campaign] {name}: already OK in {run_dir}, skipped (--skip-ok)", flush=True)
            continue
        inp = make_case(name, run_dir / "input", cases_file=cases_file, overrides=overrides)
        check_size(inp, cfg_dir / "code" / "SIZE.h")
        print(f"[run_campaign] {name}: running in {run_dir}", flush=True)
        sh([RUN_SH, build_dir, inp, run_dir, np_])
        st1 = _status(run_dir)
        results[name] = st1.get("state", "NO_STATUS") if st1 else "NO_STATUS"
        left = other_mitgcm_processes(pgrep)
        if left:
            raise RuntimeError(f"processes left after {name}: " + " | ".join(left))
        if is_two_stage(inp):
            print(f"[run_campaign] {name}: stage 1 {results[name]}; stage 2 in "
                  f"{run_dir / 'stage2'}", flush=True)
            results[name] = run_stage2(run_dir, inp, build_dir, np_, sh)
            left = other_mitgcm_processes(pgrep)
            if left:
                raise RuntimeError(f"processes left after {name} stage 2: " + " | ".join(left))
        else:
            n_exp = None
            if st1:
                d = (inp / "data").read_text()
                n_exp = _nml_int(d, "nIter0") + _nml_int(d, "nTimeSteps")
            ok = bool(st1 and st1.get("state") == "OK")
            _write_final(run_dir, results[name], {"1": st1}, n_exp,
                         None if ok else "stage 1 not OK")
        print(f"[run_campaign] {name}: {results[name]}", flush=True)
    return results


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config", required=True)
    ap.add_argument("--cases", required=True, help="fnmatch glob over case names")
    ap.add_argument("--np", type=int, default=1, dest="np_")
    ap.add_argument("--end-time", type=float, default=None, help="override endTime [s]")
    ap.add_argument("--run-suffix", default="", help="appended to each run directory name")
    ap.add_argument("--runs-root", type=Path, default=RUNS_ROOT)
    ap.add_argument("--build-root", type=Path, default=BUILD_ROOT)
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE",
                    help="override a numeric case parameter (repeatable)")
    ap.add_argument("--dry-run", action="store_true", help="list the cases and exit")
    ap.add_argument("--skip-ok", action="store_true",
                    help="do not rerun cases already OK (same deltaT/endTime); skip an up-to-date build")
    a = ap.parse_args(argv)
    if a.dry_run:
        print("\n".join(select_cases(a.config, a.cases)))
        return 0
    ov = parse_sets(a.set)
    if a.end_time is not None:
        ov["endTime"] = a.end_time
    ov = ov or None
    res = run_campaign(a.config, a.cases, a.np_, runs_root=a.runs_root,
                       build_root=a.build_root, overrides=ov, run_suffix=a.run_suffix,
                       skip_ok=a.skip_ok)
    print(json.dumps(res, indent=2))
    return 0 if all(s == "OK" for s in res.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
